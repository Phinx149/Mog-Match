import { expect, test } from "@playwright/test";

test("settings saves display name and password across reload and login", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("Username").fill("jordan-dev");
  await page.getByLabel("Password", { exact: true }).fill("mogmatch-demo");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page).toHaveURL(/discover/);
  await page.goto("/settings");
  await expect(page.getByRole("heading", { name: "Notifications" })).toHaveCount(0);
  await page.getByRole("textbox", { name: "Display name", exact: true }).fill("Hackathon Builder");
  await page.getByRole("button", { name: "Save display name" }).click();
  await expect(page.getByRole("status")).toContainText("Display name saved");
  await expect(page.getByText("Current display name:")).toContainText("Hackathon Builder");
  await page.reload();
  await expect(page.getByRole("textbox", { name: "Display name", exact: true })).toHaveValue("Hackathon Builder");
  await page.goto("/profile");
  await expect(page.getByRole("heading", { name: "Hackathon Builder", exact: true })).toBeVisible();
  await page.goto("/settings");
  await page.getByLabel("Current password", { exact: true }).fill("wrong");
  await page.getByLabel("New password", { exact: true }).fill("hackathon-password");
  await page.getByLabel("Confirm new password").fill("different-password");
  await page.getByRole("button", { name: "Save password" }).click();
  await expect(page.getByRole("alert")).toHaveText("New passwords don't match.");
  await page.getByLabel("Confirm new password").fill("hackathon-password");
  await page.getByRole("button", { name: "Save password" }).click();
  await expect(page.getByRole("alert")).toHaveText("Current password is incorrect.");
  await expect(page).toHaveURL(/settings/);
  await page.getByLabel("Current password", { exact: true }).fill("mogmatch-demo");
  await page.getByRole("button", { name: "Save password" }).click();
  await expect(page.getByRole("status")).toContainText("Password changed");
  await expect(page.getByLabel("New password", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "Log out" }).click();
  await page.getByLabel("Username").fill("jordan-dev");
  await page.getByLabel("Password", { exact: true }).fill("mogmatch-demo");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page.getByText("Wrong username or password.")).toBeVisible();
  await page.getByLabel("Password", { exact: true }).fill("hackathon-password");
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page).toHaveURL(/\/(discover|settings)$/);
  await page.goto("/settings");
  await expect(page.getByRole("textbox", { name: "Display name", exact: true })).toHaveValue("Hackathon Builder");
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: "test-results/settings-mobile.png", fullPage: true });
});
