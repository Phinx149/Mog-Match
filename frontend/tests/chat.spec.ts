import { expect, test, type Page } from "@playwright/test";
import { readFile } from "node:fs/promises";

async function login(page: Page, username: string, password: string) {
  await page.goto("/login");
  await page.getByLabel("Username").fill(username);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await expect(page).toHaveURL(/discover/);
}

test("request → accept → bidirectional WebSocket chat → shared plan → reload → mobile", async ({ browser }) => {
  const one = await browser.newContext();
  const two = await browser.newContext();
  const sender = await one.newPage();
  const recipient = await two.newPage();
  const errors: string[] = [];
  const realtimeFrames: string[] = [];
  sender.on("websocket", (ws) => ws.on("framereceived", (frame) => realtimeFrames.push(String(frame.payload))));
  sender.on("pageerror", (error) => errors.push(error.message));
  recipient.on("pageerror", (error) => errors.push(error.message));
  await login(sender, "user1", "123");
  await login(recipient, "user2", "234");
  await sender.goto("/match");
  await sender.getByRole("button", { name: "Match request", exact: true }).click();
  await sender.getByLabel(/Say hi/).fill("Want to build an accessible study planner?");
  await sender.getByRole("button", { name: "Send match request" }).click();
  await expect(sender.getByText("Invite sent · waiting")).toBeVisible();
  await recipient.goto("/inbox");
  await recipient.getByRole("button", { name: /^Requests/ }).click();
  await recipient.getByRole("button", { name: "Accept & chat" }).click();
  await expect(recipient.getByRole("heading", { name: "Test User One" })).toBeVisible();
  await sender.goto("/inbox");
  await sender.getByRole("button", { name: /Test User Two/ }).click();
  await sender.getByRole("textbox", { name: "Message Test User Two" }).fill("Let's use React and Flask for a weekend MVP.");
  await sender.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(recipient.getByRole("log").getByText("Let's use React and Flask for a weekend MVP.")).toBeVisible();
  await recipient.getByRole("textbox", { name: "Message Test User One" }).fill("Agreed. Keep it accessible and free to host.");
  await recipient.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(sender.getByRole("log").getByText("Agreed. Keep it accessible and free to host.")).toBeVisible();
  expect(realtimeFrames.some((frame) => frame.includes("chat:message"))).toBeTruthy();
  await sender.getByRole("button", { name: "Project studio" }).click();
  const studio = sender.getByRole("complementary", { name: "Shared project studio" });
  const resizer = sender.getByRole("separator", { name: "Resize project studio" });
  await expect(resizer).toBeVisible();
  const originalWidth = (await studio.boundingBox())!.width;
  const handle = (await resizer.boundingBox())!;
  await sender.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await sender.mouse.down();
  await sender.mouse.move(handle.x + handle.width / 2 - 140, handle.y + handle.height / 2, { steps: 8 });
  await sender.mouse.up();
  await expect.poll(async () => (await studio.boundingBox())!.width).toBeGreaterThan(originalWidth + 120);
  await resizer.press("Home");
  await expect.poll(async () => (await studio.boundingBox())!.width).toBe(320);
  await resizer.press("ArrowLeft");
  await expect.poll(async () => (await studio.boundingBox())!.width).toBe(352);
  await resizer.press("End");
  expect((await sender.getByRole("log").boundingBox())!.width).toBeGreaterThanOrEqual(299);
  const expandedWidth = (await studio.boundingBox())!.width;
  await sender.getByRole("button", { name: "Close project studio" }).click();
  await sender.getByRole("button", { name: "Project studio" }).click();
  await expect.poll(async () => (await studio.boundingBox())!.width).toBe(expandedWidth);
  await sender.getByLabel("Direction or constraints (optional)").fill("No paid hosting, two-day MVP.");
  await sender.getByRole("button", { name: "Generate project idea", exact: true }).click();
  await expect(sender.getByRole("heading", { name: "StudySprint", exact: true })).toBeVisible();
  const documentPanel = sender.getByRole("tabpanel", { name: "Document", exact: true });
  expect((await documentPanel.boundingBox())!.height).toBeGreaterThan((await studio.boundingBox())!.height * 0.75);
  const titleBox = (await sender.getByRole("heading", { name: "StudySprint", exact: true }).boundingBox())!;
  expect(titleBox.y - (await documentPanel.boundingBox())!.y).toBeLessThan(60);
  const chatBox = (await sender.getByRole("region", { name: "Chat with Test User Two", exact: true }).boundingBox())!;
  const navBox = (await sender.getByRole("navigation").boundingBox())!;
  expect(navBox.y - (chatBox.y + chatBox.height)).toBeGreaterThanOrEqual(0);
  expect(navBox.y - (chatBox.y + chatBox.height)).toBeLessThanOrEqual(10);
  expect(await sender.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1)).toBeTruthy();
  const downloadEvent = sender.waitForEvent("download");
  await sender.getByRole("button", { name: "Download design document" }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe("studysprint-v1.md");
  const designDoc = await readFile((await download.path())!, "utf8");
  expect(designDoc).toContain("# StudySprint");
  expect(designDoc).toContain("## Architecture");
  expect(designDoc).toContain("## Tech stack");
  expect(designDoc).toContain("## Build plan");
  await sender.screenshot({ path: "test-results/chat-desktop.png", fullPage: true });
  await recipient.getByRole("button", { name: "Project studio" }).click();
  await expect(recipient.getByRole("heading", { name: "StudySprint", exact: true })).toBeVisible();
  const originalVersion = await sender.getByLabel("Project plan version").inputValue();
  await sender.getByRole("tab", { name: "Ask AI", exact: true }).click();
  await recipient.getByRole("tab", { name: "Ask AI", exact: true }).click();
  await sender.getByRole("button", { name: "Why this architecture?", exact: true }).click();
  await sender.getByRole("button", { name: "Send to project assistant" }).click();
  await expect(sender.getByRole("log", { name: "AI discussion" }).getByText(/React and Flask fit both developers/)).toBeVisible();
  await expect(recipient.getByRole("log", { name: "AI discussion" }).getByText(/React and Flask fit both developers/)).toBeVisible();
  await expect(sender.getByLabel("Project plan version").locator("option")).toHaveCount(1);
  await expect(sender.getByRole("button", { name: "Save as new version" })).toHaveCount(0);
  // Respect the shared AI-request cooldown before requesting the revision.
  await sender.waitForTimeout(5100);
  await sender.getByRole("button", { name: "Propose changes", exact: true }).click();
  await sender.getByRole("textbox", { name: "Message the project assistant" }).fill("Simplify this into a weekend MVP.");
  await sender.getByRole("button", { name: "Send to project assistant" }).click();
  await expect(sender.getByText("Revision preview · based on version 1", { exact: true })).toBeVisible();
  await expect(sender.getByLabel("Project plan version").locator("option")).toHaveCount(1);
  await sender.getByText(/Review \d+ changed sections/).click();
  const architectureChange = sender.locator("summary").filter({ hasText: /^Architecture$/ });
  await architectureChange.click();
  await expect(architectureChange.locator("..").getByText("A single Flask service serves the React client and stores study goals in SQLite.", { exact: true })).toBeVisible();
  await sender.screenshot({ path: "test-results/studio-ai-preview.png", fullPage: true });
  await sender.getByRole("button", { name: "Save as new version", exact: true }).click();
  await expect(sender.getByRole("heading", { name: "StudySprint Weekend", exact: true })).toBeVisible();
  await expect(sender.getByRole("tab", { name: "Document", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(sender.getByLabel("Project plan version").locator("option")).toHaveCount(2);
  await expect(recipient.getByLabel("Project plan version")).toHaveValue(originalVersion);
  await expect(recipient.getByText("Saved as a shared version", { exact: true })).toBeVisible();
  await sender.getByLabel("Project plan version").selectOption(originalVersion);
  await expect(sender.getByRole("heading", { name: "StudySprint", exact: true })).toBeVisible();
  await sender.getByRole("tab", { name: "Ask AI", exact: true }).click();
  await expect(sender.getByText("Saved as a shared version", { exact: true })).toBeVisible();
  await sender.getByRole("tab", { name: "Document", exact: true }).click();
  await sender.getByLabel("Project plan version").selectOption({ index: 0 });
  const revisionDownloadEvent = sender.waitForEvent("download");
  await sender.getByRole("button", { name: "Download design document" }).click();
  const revisedDownload = await revisionDownloadEvent;
  expect(revisedDownload.suggestedFilename()).toBe("studysprint-weekend-v2.md");
  expect(await readFile((await revisedDownload.path())!, "utf8")).toContain("A single Flask service");
  await sender.reload();
  await expect(sender.getByRole("log").getByText("Agreed. Keep it accessible and free to host.")).toBeVisible();
  await sender.setViewportSize({ width: 390, height: 844 });
  expect(await sender.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight + 1)).toBeTruthy();
  await expect(sender.getByRole("textbox", { name: "Message Test User Two" })).toBeVisible();
  expect(await sender.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await sender.screenshot({ path: "test-results/chat-mobile.png", fullPage: true });
  await sender.getByRole("button", { name: "Project studio" }).click();
  await expect(resizer).toBeHidden();
  await expect(sender.getByRole("button", { name: "Download design document" })).toBeVisible();
  expect(await sender.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await sender.screenshot({ path: "test-results/studio-mobile.png", fullPage: true });
  await sender.getByRole("tab", { name: "Ask AI", exact: true }).click();
  await expect(sender.getByRole("textbox", { name: "Message the project assistant" })).toBeInViewport();
  expect(await sender.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await sender.screenshot({ path: "test-results/studio-ai-mobile.png", fullPage: true });
  await sender.getByRole("tab", { name: "Document", exact: true }).click();
  await sender.getByRole("button", { name: "Close project studio" }).click();
  await sender.getByRole("button", { name: "Back to conversations" }).click();
  await sender.getByRole("button", { name: /^Requests/ }).click();
  await expect(sender.getByRole("heading", { name: "Match requests" })).toBeVisible();
  expect(errors).toEqual([]);
  await one.close(); await two.close();
});
